/**
 * Writes src/data/questionIds.ts — the id of every Learn question and each
 * topic's question count, without the questions. Screens that only need "does
 * this question still exist?" (Home's and Progress's review counts) or "how
 * many questions in this topic?" (`TOPICS[].questionsCount`) read it instead of
 * the ~1 MB bank, so they open without downloading it (code splitting).
 *
 * Run after adding or removing a question: `npm run learn:question-ids`.
 * `src/data/__tests__/questionIds.test.ts` fails while the file is stale.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { QUESTIONS } from '../../src/data/questions';
import { computeTopicSkillCoverage, computeRegistryTopicSkillCoverage } from '../../src/services/coach/topicSkillCoverage';

export function renderQuestionIds(questions: ReadonlyArray<{ id: string; topicKey: string; demands?: { structures?: readonly string[] } }>): string {
  const sorted = [...new Set(questions.map((q) => q.id))].sort();
  const lines = sorted.map((id) => `  ${JSON.stringify(id)},`).join('\n');
  const counts: Record<string, number> = {};
  for (const q of questions) counts[q.topicKey] = (counts[q.topicKey] ?? 0) + 1;
  const countLines = Object.keys(counts)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${counts[k]},`)
    .join('\n');
  const sortCov = (cov: Record<string, Record<string, number>>) =>
    Object.fromEntries(Object.keys(cov).sort().map((k) => [k, Object.fromEntries(Object.keys(cov[k]).sort().map((s) => [s, cov[k][s]]))]));
  const coverage = JSON.stringify(sortCov(computeTopicSkillCoverage(questions)), null, 2);
  const coverageV2 = JSON.stringify(sortCov(computeRegistryTopicSkillCoverage(questions)), null, 2);
  return `// GENERATED by scripts/authoring/buildQuestionIds.ts (npm run learn:question-ids) — do not edit.
// The Learn bank's ids and per-topic counts, so a screen can use them without downloading the bank.
export const QUESTION_IDS: ReadonlySet<string> = new Set([
${lines}
]);

export const QUESTION_COUNT_BY_TOPIC: Readonly<Record<string, number>> = {
${countLines}
};

// Per topic, how many questions practise each coach skill (services/coach/topicSkillCoverage.ts).
export const TOPIC_SKILL_COVERAGE: Readonly<Record<string, Readonly<Record<string, number>>>> = ${coverage};

// The same count from the learner model's skill registry (domain/learnerModel/skills.ts, learner-model §1).
// Read only while a learner-model reader flag is live; a superset of the table above.
export const TOPIC_SKILL_COVERAGE_V2: Readonly<Record<string, Readonly<Record<string, number>>>> = ${coverageV2};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL('../../src/data/questionIds.ts', import.meta.url));
  writeFileSync(out, renderQuestionIds(QUESTIONS));
  console.log(`[question-ids] wrote ${QUESTIONS.length} ids to src/data/questionIds.ts`);
}
