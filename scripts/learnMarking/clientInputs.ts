/**
 * Learn marking ladder (learn-marking test protocol, "Harness"): what the real
 * Learn client would send with each of the 22 pre-registered test answers.
 *
 * The backend harness (backend/scripts/learn_marking_eval.py) must use "the
 * depth the client would compute" — and, for the same prompt, the client's
 * DETERMINISTIC SIGNALS. Both come from client code (the offline evaluator's 23
 * rules, the demand detectors), so instead of a Python port that could drift,
 * this runs the real functions (src/services/api/feedbackRequestHints.ts) over
 * backend/tests/fixtures/learn_marking_eval_v1/answers.json and writes
 * client_inputs.json beside it. Each entry carries the transcript's SHA-256, so
 * the harness refuses an entry whose answer text has changed.
 *
 *   npm run learn:marking-inputs            # write
 *   npm run learn:marking-inputs -- --check # exit 1 if the file is stale
 *
 * backend/ is a separate git repo — commit and push it separately (CLAUDE.md).
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getQuestionById } from '../../src/data/questions';
import { demandsVersion } from '../../src/data/learn/demandsManifest';
import { buildDemandSignals, buildRequestDepth } from '../../src/services/api/feedbackRequestHints';
import { classifyTier } from '../../src/services/coaching/responseTier';

const __dirname = dirname(fileURLToPath(import.meta.url));
const FIXTURE_DIR = join(__dirname, '..', '..', 'backend', 'tests', 'fixtures', 'learn_marking_eval_v1');
const ANSWERS = join(FIXTURE_DIR, 'answers.json');
const OUT = join(FIXTURE_DIR, 'client_inputs.json');

interface FixtureAnswer {
  id: string;
  questionId: string;
  transcript: string;
}

export function buildClientInputs(answers: FixtureAnswer[]): Record<string, unknown> {
  const entries: Record<string, unknown> = {};
  for (const answer of answers) {
    const question = getQuestionById(answer.questionId);
    if (!question) throw new Error(`Unknown Learn question ${answer.questionId} (answer ${answer.id})`);
    if (!question.demands) throw new Error(`Question ${answer.questionId} has no demands; the harness needs them resolved`);
    entries[answer.id] = {
      questionId: answer.questionId,
      transcriptSha256: createHash('sha256').update(answer.transcript, 'utf8').digest('hex'),
      depth: buildRequestDepth(answer.transcript, question, classifyTier(answer.transcript)),
      demandSignals: buildDemandSignals(answer.transcript, question),
    };
  }
  return {
    about:
      'Generated by the frontend repo\'s `npm run learn:marking-inputs` (scripts/learnMarking/clientInputs.ts) — never hand-edit. ' +
      'The depth and DETERMINISTIC SIGNALS the real Learn client sends with each answer.',
    demandsVersion,
    answers: entries,
  };
}

function main(): void {
  if (!existsSync(ANSWERS)) {
    console.error(`No test set at ${ANSWERS} (is backend/ checked out or symlinked?)`);
    process.exit(1);
  }
  const fixture = JSON.parse(readFileSync(ANSWERS, 'utf8')) as { answers: FixtureAnswer[] };
  const text = `${JSON.stringify(buildClientInputs(fixture.answers), null, 2)}\n`;
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error(`${OUT} is stale — run npm run learn:marking-inputs and commit backend/.`);
      process.exit(1);
    }
    console.log('client_inputs.json is current.');
    return;
  }
  writeFileSync(OUT, text, 'utf8');
  console.log(`Wrote ${fixture.answers.length} entries to ${OUT}.`);
  console.log('Remember: backend/ is a separate git repo — commit and push it separately (CLAUDE.md).');
}

main();
