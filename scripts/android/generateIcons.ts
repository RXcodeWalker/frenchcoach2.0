/**
 * Renders every app icon from `iconArt.ts` (run: `npm run android:icons`).
 *
 *   android/app/src/main/res legacy launcher PNGs (Android < 8) and the vector drawables
 *                            (adaptive foreground, themed icon, notification icon, splash)
 *   android/store/           the 512×512 Play Store listing icon
 *
 * The website's own icons (public/icons/) belong to the offline/install work and are not
 * written here. PNGs are rendered by the pre-installed Chromium (Playwright). Commit the output;
 * nothing renders icons at build time.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { fPathData108, maskableIconSvg, roundedIconSvg } from './iconArt';
import { readAppConfig } from './appConfig';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const RES = join(ROOT, 'android/app/src/main/res');

const LEGACY_DENSITIES: [string, number][] = [
  ['mdpi', 48],
  ['hdpi', 72],
  ['xhdpi', 96],
  ['xxhdpi', 144],
  ['xxxhdpi', 192],
];

function write(path: string, data: string | Buffer) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, data);
  console.log('  wrote', path.replace(ROOT, ''));
}

function vectorXml(body: string): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android/generateIcons.ts — do not edit by hand. -->
${body}
`;
}

function writeVectorDrawables() {
  const { brandStart, brandEnd } = readAppConfig().colors;
  const f = fPathData108();
  // Adaptive-icon foreground: white F, transparent around it (the background layer is the gradient).
  write(
    join(RES, 'drawable/ic_launcher_foreground.xml'),
    vectorXml(`<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFF" android:pathData="${f}"/>
</vector>`),
  );
  // Themed (monochrome) icon, Android 13+: the launcher tints the shape.
  write(
    join(RES, 'drawable/ic_launcher_monochrome.xml'),
    vectorXml(`<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#000000" android:pathData="${f}"/>
</vector>`),
  );
  // Adaptive-icon background: the brand gradient.
  write(
    join(RES, 'drawable/ic_launcher_background.xml'),
    vectorXml(`<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="315" android:startColor="${brandStart}" android:endColor="${brandEnd}"/>
</shape>`),
  );
  // Notification icon: Android shows it as a white silhouette, so the F alone.
  write(
    join(RES, 'drawable/ic_notification.xml'),
    vectorXml(`<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FFFFFF" android:pathData="${f}"/>
</vector>`),
  );
  // Splash image (shown while Chrome starts): the full icon, gradient square + F.
  write(
    join(RES, 'drawable/splash.xml'),
    vectorXml(`<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="144dp" android:height="144dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M24,0h60a24,24 0,0 1,24 24v60a24,24 0,0 1,-24 24h-60a24,24 0,0 1,-24 -24v-60a24,24 0,0 1,24 -24z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="${brandStart}"/>
                <item android:offset="1" android:color="${brandEnd}"/>
            </gradient>
        </aapt:attr>
    </path>
    <path android:fillColor="#FFFFFF" android:pathData="${f}"/>
</vector>`),
  );
  write(
    join(RES, 'mipmap-anydpi-v26/ic_launcher.xml'),
    vectorXml(`<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>`),
  );
}

async function main() {
  console.log('Rendering icons…');
  const browser = await chromium.launch();
  const page = await browser.newPage({ deviceScaleFactor: 1 });

  const render = async (svg: string, size: number, opaque: boolean): Promise<Buffer> => {
    await page.setViewportSize({ width: size, height: size });
    const sized = svg.replace('<svg ', `<svg width="${size}" height="${size}" `);
    await page.setContent(
      `<!doctype html><html><body style="margin:0;background:transparent;overflow:hidden">${sized}</body></html>`,
    );
    return page.screenshot({ omitBackground: !opaque, clip: { x: 0, y: 0, width: size, height: size } });
  };

  const rounded = roundedIconSvg();
  const maskable = maskableIconSvg();

  write(join(ROOT, 'android/store/play-icon-512.png'), await render(maskable, 512, true));
  for (const [density, size] of LEGACY_DENSITIES) {
    write(join(RES, `mipmap-${density}/ic_launcher.png`), await render(rounded, size, false));
  }

  await browser.close();
  writeVectorDrawables();
  console.log('Done.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
