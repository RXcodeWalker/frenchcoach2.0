import { REBUILD_QUESTIONS } from '../../data/rebuildQuestions';
import { acceptedOrders, tileText, tokenKey } from '../sentenceRebuilder/engine';
import type { RebuildQuestion } from '../../types';

/**
 * The Daily Challenge's item bank (daily-challenge-and-leagues §2.2), as the
 * server stores it.
 *
 * The items are the Sentence Rebuilder's curated sentences (`data/rebuildQuestions.ts`:
 * hand-checked word orders, `alternatives` and decoys, pinned by its own bank test), so
 * there is one sentence bank and one word-order rule. This module turns each one into the
 * row `daily_challenge_bank` holds: the tiles as they read on screen, the comparison key of
 * each tile and every accepted order as keys. The server marks an answer by comparing keys
 * only — it never re-implements `tokenKey`.
 *
 * Only the seed generator (`scripts/dailyChallenge/generateBankSeed.ts`) and tests import
 * this file. The Daily Challenge screen never does: it receives shuffled tiles from the
 * server and never holds an answer key.
 */

export interface DailyChallengeBankItem {
  id: string;
  english: string;
  french: string;
  explanation: string;
  theme: string;
  difficulty: 1 | 2 | 3;
  /** Display text: the sentence's words in order, then the decoys. */
  tiles: string[];
  /** The comparison key of each tile (same length and order as `tiles`). */
  tileKeys: string[];
  /** How many tiles a correct answer places (the decoys are the rest). */
  wordCount: number;
  /** Every accepted order, as keys; the main order first. */
  acceptedOrders: string[][];
}

export function toBankItem(q: RebuildQuestion): DailyChallengeBankItem {
  const real = q.fragments.map((word, i) => tileText(word, i === 0));
  // Decoys read like a mid-sentence word (no opening capital), exactly as the rebuilder shows them.
  const decoys = (q.distractors ?? []).map(word => tileText(word, true));
  const keys = [...q.fragments, ...(q.distractors ?? [])].map(tokenKey);
  return {
    id: q.id,
    english: q.english,
    french: q.french,
    explanation: q.explanation,
    theme: q.theme,
    difficulty: q.difficulty,
    tiles: [...real, ...decoys],
    tileKeys: keys,
    wordCount: q.fragments.length,
    acceptedOrders: acceptedOrders(q),
  };
}

export const DAILY_CHALLENGE_BANK: readonly DailyChallengeBankItem[] = REBUILD_QUESTIONS.map(toBankItem);

// ── SQL seed ──────────────────────────────────────────────────────────────────

const sqlText = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const sqlTextArray = (xs: readonly string[]): string => `ARRAY[${xs.map(sqlText).join(', ')}]::text[]`;
const sqlJson = (v: unknown): string => `${sqlText(JSON.stringify(v))}::jsonb`;

/**
 * The full seed for `daily_challenge_bank`: an upsert of every item, then every row no
 * longer in the bank is switched off (never deleted — a past day's set still names it).
 * The newest `*_daily_challenge_bank_seed.sql` migration therefore defines the whole bank;
 * `dailyChallengeSeedParity.test.ts` regenerates it and compares.
 */
export function renderBankSeedSql(items: readonly DailyChallengeBankItem[] = DAILY_CHALLENGE_BANK): string {
  const rows = items.map(
    it =>
      `  (${sqlText(it.id)}, ${sqlText(it.english)}, ${sqlText(it.french)}, ${sqlText(it.explanation)}, ` +
      `${sqlText(it.theme)}, ${it.difficulty}, ${sqlTextArray(it.tiles)}, ${sqlTextArray(it.tileKeys)}, ` +
      `${it.wordCount}, ${sqlJson(it.acceptedOrders)})`,
  );
  return [
    '/*',
    '  # Daily Challenge bank seed (GENERATED — do not hand-edit)',
    '',
    '  Generated by `npm run daily-challenge:seed` in the main repo from',
    '  src/data/rebuildQuestions.ts via src/features/dailyChallenge/bank.ts.',
    '  To change the bank: edit the sentences there, run the script with a new',
    '  migration file name, and apply that migration. The newest file with this',
    '  suffix defines the whole bank (main repo dailyChallengeSeedParity.test.ts).',
    '*/',
    '',
    'INSERT INTO public.daily_challenge_bank',
    '  (id, english, french, explanation, theme, difficulty, tiles, tile_keys, word_count, accepted_orders)',
    'VALUES',
    rows.join(',\n'),
    'ON CONFLICT (id) DO UPDATE SET',
    '  english = EXCLUDED.english, french = EXCLUDED.french, explanation = EXCLUDED.explanation,',
    '  theme = EXCLUDED.theme, difficulty = EXCLUDED.difficulty, tiles = EXCLUDED.tiles,',
    '  tile_keys = EXCLUDED.tile_keys, word_count = EXCLUDED.word_count,',
    '  accepted_orders = EXCLUDED.accepted_orders, active = true, updated_at = now();',
    '',
    `UPDATE public.daily_challenge_bank SET active = false, updated_at = now()`,
    `WHERE active AND id <> ALL (${sqlTextArray(items.map(it => it.id))});`,
    '',
  ].join('\n');
}
