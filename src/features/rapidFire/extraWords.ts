import type { WordLevel } from './wordBank';

/**
 * Hand-authored Rapid Fire cards, on top of the ones derived from Learn, Emoji
 * Master and the minigames (`wordBank.ts`). Each card is
 * `[English shown, accepted French (first one is shown as the answer), level]`.
 *
 * Authoring rules (`wordBank.test.ts` holds the mechanical ones):
 *  - the English alone must settle the French: disambiguate in brackets
 *    ("to know (a fact)"), and list every genuinely accepted alternative;
 *  - nouns carry their article ("le stylo", "l'école"), because the judge
 *    requires it;
 *  - no brackets, slashes or "..." in the French (those are glossary notation);
 *  - accents are written correctly even though typing them is optional;
 *  - avoid "œ" (hard to type): pick another word;
 *  - level 1 = A1 survival, 2 = IGCSE core, 3 = stretch.
 */
export type Card = readonly [english: string, french: string | readonly string[], level: WordLevel];

